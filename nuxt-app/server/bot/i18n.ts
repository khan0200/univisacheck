/**
 * Translates a key based on the language.
 * Interpolates parameters like {{param}} with corresponding values.
 *
 * @param lang - Target language ('uz' or 'en')
 * @param key - Translation key
 * @param params - Optional parameters for interpolation
 * @returns Translated string
 */
export function t(lang: Lang, key: string, params?: Record<string, string | number>): string {
  let str = (translations[lang] as Record<string, string>)?.[key] || (translations['uz'] as Record<string, string>)?.[key] || key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      str = str.replace(new RegExp(`{{${k}}}`, 'g'), String(v));
    }
  }
  return str;
}
